from prometheus_client import Counter, Histogram, Gauge
REQUESTS=Counter("kyc_requests_total","KYC processing requests",["outcome"])
REQUEST_LATENCY=Histogram("kyc_request_duration_seconds","End-to-end processing duration",buckets=(1,2,5,10,20,30,60,120))
TOOL_CALLS=Counter("kyc_tool_calls_total","KYC tool calls",["tool","outcome"])
EXTRACTION_FIELDS=Counter("kyc_extraction_fields_total","Extracted field outcomes",["field","result"])
EVAL_ACCURACY=Gauge("kyc_extraction_accuracy","Latest labelled field-level accuracy")
DRIFT_ACCURACY=Gauge("kyc_ocr_drift_accuracy","Rolling labelled OCR accuracy")
DRIFT_STATE=Gauge("kyc_ocr_drift_state","0=healthy, 1=warning, 2=critical")
LLM_TOKENS=Counter("kyc_llm_tokens_total","LLM tokens",["direction","model"])
LLM_COST=Counter("kyc_llm_cost_usd_total","Estimated LLM cost USD",["model"])
MANUAL_REVIEW=Counter("kyc_manual_review_total","Applications routed to human review",["reason"])
APPLICATION_DECISIONS=Counter("kyc_application_decisions_total","Preliminary onboarding decisions",["status"])
DOCUMENTS_RECEIVED=Counter("kyc_documents_received_total","Applicant documents received",["document_type"])
DOCUMENT_REQUESTS=Counter("kyc_document_requests_total","Document requests sent",["document_type"])
DUPLICATE_REQUESTS_PREVENTED=Counter("kyc_duplicate_document_request_attempts_prevented_total","Duplicate document requests blocked",["document_type"])
ONBOARDING_SLO=Gauge("kyc_onboarding_no_duplicate_rerequest_slo_ratio","Share of applications reaching a decision without duplicate document re-request")
